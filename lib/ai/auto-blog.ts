/** How many automatic posts per ISO week. */
export const AUTO_BLOG_PER_WEEK = 2;

/** "publish" puts the post live straight away; anything else saves it as a draft for the admin to publish. */
export function autoBlogMode(): "publish" | "draft" {
  return (process.env.BLOG_AUTOPUBLISH ?? "").trim().toLowerCase() === "publish" ? "publish" : "draft";
}

function weekStart(now = new Date()) {
  const d = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
  const day = d.getUTCDay() || 7; // Monday = 1
  d.setUTCDate(d.getUTCDate() - (day - 1));
  return d;
}

function pick<T>(items: T[], n: number) {
  return [...items].sort(() => Math.random() - 0.5).slice(0, n);
}

function parseJson(text: string): Record<string, unknown> | null {
  const raw = text.replace(/^```(?:json)?\s*|\s*```$/g, "").trim();
  try {
    return JSON.parse(raw) as Record<string, unknown>;
  } catch {
    const m = /\{[\s\S]*\}/.exec(raw);
    if (!m) return null;
    try {
      return JSON.parse(m[0]) as Record<string, unknown>;
    } catch {
      return null;
    }
  }
}

/**
 * Writes one SEO/AEO/GEO-friendly article with Gemini from the live catalogue (no prices, no invented facts) and
 * saves it to the blog. Returns the slug. Needs the Growth agent (owner approval) and a Gemini key.
 */
export async function generateBlogPost(options: { publish?: boolean; topic?: string } = {}) {
  if (!agentEnabled("growth")) throw new Error("The Growth agent is not enabled (needs approval). No blog post was written.");
  if (!geminiConfigured()) throw new Error("GEMINI_API_KEY is not set.");
  const products = (await getStorefrontProducts()).filter((p) => p.name && p.slug);
  if (!products.length) throw new Error("No products in the catalogue to write about.");
  const category = pick(defaultBlogCategories, 1)[0];
  const featured = pick(products, 3);
  const origin = getSiteOrigin();
  const col = await blogCollection();
  const recent = await col.find({}, { projection: { title: 1 } }).sort({ createdAt: -1 }).limit(30).toArray();

  const facts = featured
    .map((p) => `- ${p.name} | material: ${p.material || "brass"} | page: ${origin}/product/${p.slug} | ${String(p.description || "").slice(0, 300)}`)
    .join("\n");
  const prompt = `Write one new blog article for Marina Muse International (handcrafted nautical and brass products from India; retail, wholesale, B2B and custom manufacturing).
Topic area: ${options.topic || category.name}.
Products you may mention (use ONLY these facts, never invent specifications, never state prices, stock or discounts):
${facts}
Do not repeat these existing titles: ${recent.map((r) => String(r.title)).join(" | ") || "none"}.
SEO/AEO/GEO: a clear, search-friendly title (max 65 characters); start with a 2-sentence direct answer to the main question; use short sections with "## " headings; include a short "## Frequently asked questions" section with 3 questions and answers; mention the product pages as plain links; 600-900 words; British English; warm, expert tone.
Return ONLY JSON: {"title": string, "excerpt": string (max 155 characters, meta description), "body": string (the article, paragraphs separated by a blank line, headings start with "## ")}`;

  const result = await generateFor("growth", "blog", {
    system: "You are the content writer for Marina Muse International. Output valid JSON only.",
    turns: [{ role: "user", text: prompt }],
    temperature: 0.7,
    maxOutputTokens: 4096,
  });
  if (!result.ok) throw new Error(`Gemini could not write the article: ${result.error ?? "unknown error"}`);
  const json = parseJson(result.text);
  const title = String(json?.title ?? "").trim();
  const body = String(json?.body ?? "").trim();
  if (!title || body.length < 400) throw new Error("Gemini returned an incomplete article; nothing was saved.");

  const publish = options.publish ?? autoBlogMode() === "publish";
  const input = readBlogInput({
    title,
    excerpt: String(json?.excerpt ?? "").trim(),
    body,
    category: category.slug,
    image: featured[0]?.image || "/blog-slide.jpeg",
    link: `${origin}/product/${featured[0].slug}`,
    published: publish,
  });
  let slug = input.slug;
  if (await col.findOne({ slug })) slug = `${slug}-${Date.now().toString(36).slice(-4)}`;
  const now = new Date();
  await col.insertOne({ ...input, slug, autoGenerated: true, createdAt: now, updatedAt: now } as never);
  return { slug, title, published: publish };
}

/** Called by the scheduled job: keeps the week at AUTO_BLOG_PER_WEEK automatic posts (Monday and Thursday onwards). */
export async function runWeeklyAutoBlog(now = new Date()) {
  if (!agentEnabled("growth") || !geminiConfigured()) return { skipped: "growth agent or Gemini not enabled" };
  const col = await blogCollection();
  const done = await col.countDocuments({ autoGenerated: true, createdAt: { $gte: weekStart(now) } } as never);
  const day = now.getUTCDay() || 7;
  const due = day >= 4 ? AUTO_BLOG_PER_WEEK : 1; // first post from Monday, second from Thursday
  if (done >= due) return { skipped: `already ${done} this week` };
  const post = await generateBlogPost();
  return { created: post.slug, published: post.published };
}
