export function getProductCategory(p: Product) {
  return p.categories?.[0] || p.category || slugMap[p.slug] || collectionMap[p.collection] || "ungrouped";
}

function compactUsd(n: number) {
  if (Number.isInteger(n)) return `$${n}`;
  return `$${n.toFixed(2).replace(/\.00$/, "")}`;
}

export function formatOfferPrice(p: Product) {
  const min = p.wholesaleFrom ?? p.price;
  const max = p.price;
  if (min >= max) return `${compactUsd(max)} USD`;
  return `${compactUsd(min)}-${compactUsd(max).replace("$", "")}`;
}
